import { chromium } from 'playwright';
const url = 'http://localhost:4173/';
const out = '/tmp/claude-0/shots/';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const p = await b.newPage({ viewport: { width: 1280, height: 820 }, deviceScaleFactor: 1 });
const logs = [];
p.on('console', m => logs.push(m.type() + ': ' + m.text()));
p.on('pageerror', e => logs.push('ERR ' + e.message));
await p.goto(url);
await p.waitForTimeout(1500);
await p.screenshot({ path: out + '1-caption.png' });
await p.keyboard.type(' Hello there.');
await p.waitForTimeout(400);
await p.screenshot({ path: out + '2-typed.png' });
await p.click('text=Letter');
await p.waitForTimeout(1200);
await p.screenshot({ path: out + '3-letter.png' });
await p.click('text=See the page');
await p.waitForTimeout(900);
await p.screenshot({ path: out + '4-page.png' });
console.log(logs.join('\n'));
await b.close();
// phone
const b2 = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const m = await b2.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
await m.goto(url);
await m.waitForTimeout(1500);
await m.screenshot({ path: out + '5-phone.png' });
await m.click('text=Letter');
await m.waitForTimeout(1000);
await m.screenshot({ path: out + '6-phone-letter.png' });
await b2.close();
